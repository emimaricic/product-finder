// Writes the PrimeUI license key into a generated, git-ignored TS module.
// Source, in order: PRIMEUI_LICENSE_KEY env var → frontend/.env → none
// (primeui-license.ts then falls back to the committed Community key).
// Runs on postinstall / prestart / prebuild; CI and Docker pass the env var.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

function fromDotEnv() {
  const file = resolve(root, '.env');
  if (!existsSync(file)) return '';
  const line = readFileSync(file, 'utf8')
    .split(/\r?\n/)
    .find((l) => l.trim().startsWith('PRIMEUI_LICENSE_KEY='));
  return line ? line.split('=').slice(1).join('=').trim().replace(/^['"]|['"]$/g, '') : '';
}

const key = (process.env.PRIMEUI_LICENSE_KEY ?? '').trim() || fromDotEnv();
const out = resolve(root, 'src/app/core/theme/primeui-license.generated.ts');
// In Docker, `npm ci` (postinstall) runs before src/ is copied in.
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// Generated by scripts/write-license.mjs — do not edit, not committed.\nexport const PRIMEUI_LICENSE_KEY_FROM_ENV = ${JSON.stringify(key)};\n`,
);
console.log(`[license] PrimeUI key ${key ? 'from environment' : 'not set (using committed fallback)'}`);
